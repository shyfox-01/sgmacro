"""Run the summary step live against several local models and tabulate the checker.

Evidence for the design report: how often each model's claims survive the claim
checker, and why the rejected ones were rejected. Each model gets a fresh cache
directory, so every response is generated live.

    python scripts/compare_summary_models.py            # writes docs/evidence/summary_models.{json,md}
"""

from __future__ import annotations

import json
import sys
import time
from collections import Counter
from datetime import date
from pathlib import Path

from sgmacro.llm.backends import OllamaBackend
from sgmacro.llm.summary import summarise
from sgmacro.pipeline import RunConfig, analyse, fetch_stage
from sgmacro.registry import load_registry

MODELS = [("qwen3.5:9b", False), ("qwen3.5:9b", True), ("qwen3.5:27b", False)]
OUT = Path("docs/evidence")
SCRATCH = Path("data/_scratch/summary_models") / time.strftime("%Y%m%dT%H%M%S")  # fresh per invocation


def reason_key(message: str) -> str:
    for key in ("contradicts", "mixes signal readings", "without citing a signal", "no rents signal",
                "no sales signal", "do not appear", "wording says", "wording implies", "under the", "longer than",
                "unknown fact ids", "cites no facts", "forecast"):
        if key in message:
            return key
    return message[:40]


def main() -> int:
    registry = load_registry()
    config = RunConfig(as_of=date(2026, 10, 2), offline=True)
    result = analyse(config, registry, fetch_stage(config, registry, lambda m: None))
    rows = []
    for model, think in MODELS:
        label = f"{model}{' (thinking)' if think else ''}"
        cache = SCRATCH / label.replace(":", "_").replace(" ", "_").replace("(", "").replace(")", "")
        backend = OllamaBackend(model=model, think=think)
        started = time.monotonic()
        summary = summarise(result, cache_dir=cache, backend=backend, log=lambda m: None)
        seconds = time.monotonic() - started
        claims = [c for m in summary.markets.values() for c in m.claims]
        reasons = Counter(reason_key(v) for c in claims for v in c.violations)
        rows.append({
            "model": label, "seconds": round(seconds, 1), "claims": len(claims),
            "accepted": sum(c.ok for c in claims), "rejected": sum(not c.ok for c in claims),
            "markets_on_template": [m for m, s in summary.markets.items() if s.source == "deterministic"],
            "notes": summary.notes + summary.skipped_backends + summary.execution_notes,
            "rejection_reasons": dict(reasons),
            "rejected_claims": [{"market": c.market, "text": c.text, "violations": c.violations}
                                for c in claims if not c.ok],
        })
        print(f"{label}: {rows[-1]['accepted']}/{rows[-1]['claims']} accepted in {seconds:.0f}s", file=sys.stderr)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "summary_models.json").write_text(json.dumps(rows, indent=2, ensure_ascii=False) + "\n",
                                             encoding="utf-8", newline="\n")
    lines = ["# Summary step: claim-checker outcomes by model", "",
             "Generated by `scripts/compare_summary_models.py` on the 2026-10-02 fact sheet, each model live "
             "(temperature 0, fresh cache).", "",
             "| Model | Claims | Accepted | Rejected | Markets falling back to template | Seconds |",
             "| --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        lines.append(f"| {r['model']} | {r['claims']} | {r['accepted']} | {r['rejected']} | "
                     f"{', '.join(r['markets_on_template']) or 'none'} | {r['seconds']} |")
    lines += ["", "## Fallback notes", ""]
    for r in rows:
        for note in r["notes"]:
            lines.append(f"- **{r['model']}**: {note}")
    if not any(r["notes"] for r in rows):
        lines.append("None.")
    lines += ["", "## Rejected claims", ""]
    for r in rows:
        for c in r["rejected_claims"]:
            lines.append(f"- **{r['model']}**, {c['market']}: \"{c['text']}\"  ")
            lines.append(f"  rejected because: {'; '.join(c['violations'])}")
    if not any(r["rejected_claims"] for r in rows):
        lines.append("None.")
    (OUT / "summary_models.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
